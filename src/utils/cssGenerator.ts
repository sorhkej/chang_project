/**
 * Generate CSS variables from theme spacing
 */
export function generateSpacingCSS(spacing: ThemeSpacing): string {
  const scale = spacing.scale;
  return `  /* Spacing Base */
  --spacing-base: ${spacing.base};

  /* Spacing Scale */
  --spacing-0: ${scale[0]};
  --spacing-1: ${scale[1]};
  --spacing-2: ${scale[2]};
  --spacing-3: ${scale[3]};
  --spacing-4: ${scale[4]};
  --spacing-5: ${scale[5]};
  --spacing-6: ${scale[6]};
  --spacing-8: ${scale[8]};
  --spacing-10: ${scale[10]};
  --spacing-12: ${scale[12]};
  --spacing-16: ${scale[16]};
  --spacing-20: ${scale[20]};
  --spacing-24: ${scale[24]};
  --spacing-32: ${scale[32]};
  --spacing-40: ${scale[40]};
  --spacing-48: ${scale[48]};
  --spacing-64: ${scale[64]};`;
}

/**
 * Generate complete CSS from theme
 */
export function generateCSSFromTheme(theme: Theme): string {
  return `/**
 * ${theme.name}
 * ${theme.description}
 *
 * Generated by Vue Theme Switcher
 */

:root {
${generateColorCSS(theme.colors)}

${generateTypographyCSS(theme.typography)}

${generateSpacingCSS(theme.spacing)}

${generateLayoutCSS(theme.layout)}
}`;
}

/**
 * Generate CSS with font import
 */
export function generateCSSWithFontImport(theme: Theme): string {
  let fontImport = '';

  if (theme.fontConfig) {
    const { family, weights, subsets, display } = theme.fontConfig;
    fontImport = `@import url('https://fonts.googleapis.com/css2?family=${family.replace(' ', '+')}:wght@${weights.join(';')}&subset=${subsets.join(',')}&display=${display || 'swap'}');

`;
  }

  return fontImport + generateCSSFromTheme(theme);
}

/**
 * Format timestamp for filename
 */
export function formatTimestampForFilename(): string {
  const now = new Date();
  const year = now.getFullYear();
  const month = String(now.getMonth() + 1).padStart(2, '0');
  const day = String(now.getDate()).padStart(2, '0');
  const hours = String(now.getHours()).padStart(2, '0');
  const minutes = String(now.getMinutes()).padStart(2, '0');
  const seconds = String(now.getSeconds()).padStart(2, '0');

  return `${year}${month}${day}-${hours}${minutes}${seconds}`;
}
