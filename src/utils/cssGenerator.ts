/**
 * CSS Generator utility
 *
 * Converts theme objects to CSS variables and complete CSS files.
 */

import type { Theme, ThemeColors, ThemeTypography, ThemeLayout, ThemeSpacing } from '../types/theme';

/**
 * Generate CSS variables from theme colors
 */
export function generateColorCSS(colors: ThemeColors): string {
  return `  /* Brand Colors */
  --color-primary: ${colors.primary};
  --color-secondary: ${colors.secondary};
  --color-accent: ${colors.accent};
  --color-success: ${colors.success};
  --color-warning: ${colors.warning};
  --color-error: ${colors.error};
  --color-info: ${colors.info};

  /* Background Colors */
  --color-background-primary: ${colors.background.primary};
  --color-background-secondary: ${colors.background.secondary};
  --color-background-tertiary: ${colors.background.tertiary};
  --color-background-elevated: ${colors.background.elevated};
  --color-background-overlay: ${colors.background.overlay};

  /* Text Colors */
  --color-text-primary: ${colors.text.primary};
  --color-text-secondary: ${colors.text.secondary};
  --color-text-tertiary: ${colors.text.tertiary};
  --color-text-disabled: ${colors.text.disabled};
  --color-text-inverse: ${colors.text.inverse};

  /* Border Colors */
  --color-border-default: ${colors.border.default};
  --color-border-subtle: ${colors.border.subtle};
  --color-border-strong: ${colors.border.strong};`;
}

